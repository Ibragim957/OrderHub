class OrderHubError(Exception):
    """Базовое исключение домена — удобно ловить одним except в тестах."""


class CatalogUnavailable(OrderHubError):
    """service-2 не ответил.

    Заказ создать невозможно: цены брать неоткуда, а доверять ценам клиента
    нельзя. Роут переводит это в 503.
    """


class InvalidOrderItems(OrderHubError):
    """С позициями заказа что-то не так.

    Позиции не существует, она принадлежит другому ресторану или снята с продажи.
    Роут переводит это в 400.
    """


class InvalidStatusTransition(OrderHubError):
    """Недопустимый переход между статусами заказа.

    Например, попытка отменить уже доставленный заказ. Роут переводит это в 409.
    """
